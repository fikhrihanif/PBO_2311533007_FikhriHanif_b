package model;

public class Costumer {
	String id_costumer, nama_costumer, alamat_costumer, nohp_costumer;

	public String getId_costumer() {
		return id_costumer;
	}

	public void setId_costumer(String id) {
		this.id_costumer = id;
	}

	public String getNama_costumer() {
		return nama_costumer;
	}

	public void setNama_costumer(String nama) {
		this.nama_costumer = nama;
	}

	public String getAlamat_costumer() {
		return alamat_costumer;
	}

	public void setAlamat_costumer(String alamat) {
		this.alamat_costumer = alamat;
	}

	public String getNohp_costumer() {
		return nohp_costumer;
	}

	public void setNohp_costumer(String nohp) {
		this.nohp_costumer = nohp;
	}

	
}
